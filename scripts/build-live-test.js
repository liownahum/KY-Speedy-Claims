'use strict';
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createHash } = require('node:crypto');

const root = path.resolve(__dirname, '..');
const pipeline = process.argv.includes('--pipeline');
const installer = process.argv.includes('--installer');
if (pipeline && installer) throw new Error('Choose --pipeline or --installer, not both.');
const destinationArg = process.argv.slice(2).find(arg => arg !== '--pipeline' && arg !== '--installer');
const destination = path.resolve(destinationArg || path.join(root, 'local', installer ? 'setup-workbook' : pipeline ? 'form-test' : 'live-test'));
const names = ['VoucherCore.js', 'ClaimCore.js', 'ClaimProcessor.js', 'Voucher.gs', 'Prototype.gs', 'ClaimStore.gs', 'ClaimFiles.gs', 'ClaimPipeline.gs', 'SetupWorkbook.gs'];
const script = names.map(name => '// Source: src/' + name + '\n' + fs.readFileSync(path.join(root, 'src', name), 'utf8')).join('\n\n');
const manifest = fs.readFileSync(path.join(root, 'src', 'appsscript.json'), 'utf8');
JSON.parse(manifest);
const fingerprint = createHash('sha256').update(script + '\n' + manifest).digest('hex');
const combined = '/* KY Speedy Claims ' + (installer ? 'setup-workbook' : 'manual live-test') + ' bundle. Source SHA-256: ' + fingerprint + ' */\n\n' + script;
new vm.Script(combined, { filename: 'Code.gs' });
fs.mkdirSync(destination, { recursive: true });
fs.writeFileSync(path.join(destination, 'Code.gs'), combined + '\n');
fs.writeFileSync(path.join(destination, 'appsscript.json'), manifest);
fs.copyFileSync(path.join(root, 'docs', installer ? 'setup-workbook.md' : pipeline ? 'form-pipeline-test.md' : 'manual-test.md'), path.join(destination, 'START-HERE.md'));
console.log('Built Code.gs, appsscript.json, and START-HERE.md. Source fingerprint: ' + fingerprint.slice(0, 12) + '.');
